_TRANSFORM = re.compile(
    r"rot(?P<rot>[Np\d]+)_tilt(?P<tilt>[Np\d]+)_psi(?P<psi>[Np\d]+)"
    r"deg_trans(?P<x>[Np\d]+)_(?P<y>[Np\d]+)_(?P<z>[Np\d]+)ANG"
)
