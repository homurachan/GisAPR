def decode_transform_string(s):
    def convert(value):
        value = value.replace("p", ".")
        return -float(value[1:]) if value.startswith("N") else float(value)

    match = _TRANSFORM.search(s)
    if match is None:
        # Preserve v2p6's identity-transform fallback.
        return (0.0,) * 6
    return tuple(convert(match.group(k)) for k in ("rot", "tilt", "psi", "x", "y", "z"))


def calc_weight_between_distance_rotation(diameter):
    w0 = 360.0 / np.pi / diameter
    return 1.0 / w0


def compute_weighted_overall_distance(rotation_in_degree, translation_in_angstrom, weight):
    return np.sqrt((rotation_in_degree * weight) ** 2.0 + translation_in_angstrom ** 2.0)


def DEG2RAD(x):
    # Legacy helper retained for imports; pose distances now use rotvec.
    return x / 180.0 * 3.14159265359


def Euler_angles2matrix(alpha, beta, gamma):
    alpha, beta, gamma = DEG2RAD(alpha), DEG2RAD(beta), DEG2RAD(gamma)
    ca, cb, cg = math.cos(alpha), math.cos(beta), math.cos(gamma)
    sa, sb, sg = math.sin(alpha), math.sin(beta), math.sin(gamma)
    cc, cs, sc, ss = cb * ca, cb * sa, sb * ca, sb * sa
    return [
        [cg * cc - sg * sa, cg * cs + sg * ca, -cg * sb],
        [-sg * cc - cg * sa, -sg * cs + cg * ca, sg * sb],
        [sc, ss, cb],
    ]


def CLIP(a, b, c):
    if float(a) < float(b):
        return float(b)
    if float(a) > float(c):
        return float(c)
    return float(a)


def dotProduct(v1, v2):
    if len(v1) != len(v2):
        return -9999999.0
    result = 0.0
    for a, b in zip(v1, v2):
        result += float(a) * float(b)
    return result


def calculateAngularDistance(rot1, tilt1, psi1, rot2, tilt2, psi2):
    # These names encode rotation-vector components, not Euler angles.
    # Retain v2p6's scalar SciPy calls and operation order for exact floats.
    rot1 = np.deg2rad(rot1)
    rot2 = np.deg2rad(rot2)
    tilt1 = np.deg2rad(tilt1)
    tilt2 = np.deg2rad(tilt2)
    psi1 = np.deg2rad(psi1)
    psi2 = np.deg2rad(psi2)
    r1 = np.array([rot1, tilt1, psi1])
    r2 = np.array([rot2, tilt2, psi2])
    R1 = R.from_rotvec(r1)
    R2 = R.from_rotvec(r2)
    R_rel = R1 * R2.inv()
    angle = R_rel.magnitude()
    return np.degrees(angle)


def calculateShiftDistance(x, y, z, x1, y1, z1):
    a1, a2, a3 = (x1 - x) ** 2.0, (y1 - y) ** 2.0, (z1 - z) ** 2.0
    return math.sqrt(a1 + a2 + a3)


def read_index(filename):
    # Relative entries remain relative to the working directory, as in v2p6.
    with open(filename, "r") as handle:
        paths = [line.split()[0] for line in handle if line.split()]
    if not paths:
        raise ValueError("The input index contains no search files.")
    return paths


def count_search_lines(filename, block_size=4 * 1024 * 1024):
    """Match sum(1 for line in open(filename)), using bounded text blocks."""
    if block_size < 1:
        raise ValueError("Line-count block size must be positive.")
    count, last = 0, ""
    # Default text decoding and universal newlines match v2p6, including
    # CRLF/CR input and a final line without a newline terminator.
    with open(filename, "r") as handle:
        for block in iter(lambda: handle.read(block_size), ""):
            count += block.count("\n")
            last = block[-1]
    return count + int(bool(last) and last != "\n")


def filter_search_files(paths):
    """Keep v2p6's modal line-count group and its exact file/tie order."""
    unique_paths = list(dict.fromkeys(paths))
    line_counts = {}
    last_progress = time.monotonic()
    for index, path in enumerate(unique_paths, 1):
        try:
            line_counts[path] = count_search_lines(path)
        except (OSError, UnicodeError) as exc:
            print("Warning: cannot read {}, skip. ({})".format(path, exc), flush=True)
        now = time.monotonic()
        if now - last_progress >= 15:
            print("Counted lines in {}/{} search files".format(index, len(unique_paths)), flush=True)
            last_progress = now
    if not line_counts:
        raise ValueError("No readable search files remain after v2p6 line-count filtering.")
    # Counter breaks frequency ties by the first occurrence of a line count.
    most_common_count = Counter(line_counts.values()).most_common(1)[0][0]
    clean_files = []
    for path, count in line_counts.items():
        if count == most_common_count:
            clean_files.append(path)
        else:
            print("Warning: {} has {} lines; expected {} (most common), skip.".format(
                path, count, most_common_count), flush=True)
    print("Most common line count:", most_common_count)
    print("Total files:", len(paths))
    print("Valid files:", len(clean_files))
    print("Removed files:", len(paths) - len(clean_files))
    if len(unique_paths) != len(paths):
        print("Repeated index entries ignored:", len(paths) - len(unique_paths))
    return clean_files


def sorted_file_distances(paths, best_string, diameter):
    pivot = decode_transform_string(best_string)
    weight = calc_weight_between_distance_rotation(diameter)
    pairs = []
    for path in paths:
        pose = decode_transform_string(path)
        rotation = calculateAngularDistance(*(pivot[:3] + pose[:3]))
        translation = calculateShiftDistance(*(pivot[3:] + pose[3:]))
        pairs.append((path, compute_weighted_overall_distance(rotation, translation, weight)))
    # Python's stable sort preserves index.txt order for equal distances.
    pairs.sort(key=lambda pair: pair[1])
    return pairs


def read_search_scores(filename, distance):
    """Read native-int/float64 arrays, with dict-compatible last-wins IDs."""
    serials, scores, distances = array("q"), array("d"), array("d")
    with open(filename, "r") as handle:
        for record, first in enumerate(handle, 1):
            second, third = handle.readline(), handle.readline()
            if not second or not third:
                raise ValueError("{}: incomplete three-line record {}".format(filename, record))
            try:
                fields = first.split(",", 3)
                if len(fields) < 2:
                    raise ValueError("missing serial-number field")
                if fields[0] == "['cc: '":
                    serial = int(fields[1])
                    float(fields[2])  # v2p6 validates this unused input Z score.
                    score = float(third.rsplit(",", 1)[-1].split("]", 1)[0]) / 1024.0
                    record_distance = distance
                else:
                    # v2p6 maps all non-cc records to this single sentinel.
                    serial, score = -1, 0.0
                    record_distance = 999.0
                serials.append(serial)
                scores.append(score)
                distances.append(record_distance)
            except (ValueError, IndexError, OverflowError) as exc:
                raise ValueError("{}: invalid record {}: {}".format(filename, record, exc)) from exc
    ids = np.frombuffer(serials, dtype=np.int64)
    native_int = np.dtype(int)  # v2p6 uses np.zeros(..., dtype=int).
    if native_int != ids.dtype:
        limits = np.iinfo(native_int)
        if np.any((ids < limits.min) | (ids > limits.max)):
            raise ValueError("A serial number cannot be represented by NumPy's native integer dtype.")
        ids = ids.astype(native_int)
    raw = np.frombuffer(scores, dtype=np.float64)
    dist = np.frombuffer(distances, dtype=np.float64)
    if ids.size > 1 and not np.all(ids[1:] > ids[:-1]):
        unique, first_index = np.unique(ids, return_index=True)
        if unique.size != ids.size:
            # dict(zip(...)) keeps first insertion order but the last value.
            _, reversed_first = np.unique(ids[::-1], return_index=True)
            order = np.argsort(first_index)
            last_index = (ids.size - 1 - reversed_first)[order]
            raw, dist, ids = raw[last_index], dist[last_index], unique[order]
    return ids, raw, dist


@contextmanager
def atomic_binary_file(path):
    parent = os.path.dirname(os.path.abspath(path))
    os.makedirs(parent, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".gisapr_pick_", dir=parent)
    try:
        with os.fdopen(fd, "w+b") as handle:
            yield handle
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


