#!/usr/bin/env python3
"""Select GisAPR particles; emit two complete pickles from one serialization.

Requirements: Python >= 3.8, NumPy, SciPy; Matplotlib for the distribution plot.

Example (the v2p6 command line is still accepted)::

    python read_search_txt_pick_good_v3p3.py --i index.txt \
        --best_string rotN1p0_tiltN12p2_psi4p4deg_trans2p3_8p1_N4p8ANG \
        --o fortest --diameter 40 --top_N 5 --top_N_sum_threshold 2.5

v3p3 implementation and compatibility notes
-------------------------
* Follow v2p6's file filter before sorting or scoring: count physical text
  lines, ignore unreadable files, and keep only the most common line count.
  Both shorter and longer files are excluded. Repeated path strings count
  once, in first-occurrence index order; ties between line-count frequencies
  use that same order, exactly as v2p6's dict/Counter implementation does.
  Counting uses bounded text blocks with universal-newline handling. No
  full-file readlines or temporary arrays are used. The filter is checked
  on every invocation so repaired or newly missing files affect caching.
* The filename/best_string labels remain rot/tilt/psi. Their three values
  are rotation-vector components in degrees, NOT Euler angles. Match v2p6
  using SciPy Rotation.from_rotvec(deg2rad(...)), R1 * R2.inv(), magnitude(),
  and np.degrees, with the original scalar operation order.
* Optional selected search files are written only for the retained inputs;
  excluded files are skipped throughout. v2p6's optional export reopens the
  unfiltered index, which can attempt to read a missing/truncated file again.
* Call the original standard pickle.dump once on the complete raw list.
  Its unmodified byte stream is written to the raw pickle. A validated
  streaming parser copies the same stream to the Z-score pickle, changing
  only the float64 score payloads. Keys, distances, dtype metadata, memo
  opcodes, frames and byte order all come from the standard Pickler.
* The parser learns the regular NumPy-scalar record layout from a small
  pickle generated by this runtime. It checks complete record bytes against
  the source dictionary before replacing score payloads. A boundary parser
  handles initial dtype definitions, frames and partial records. It never
  searches for arbitrary float byte strings or unpickles its input.
* One serialization normally writes both final streams at once: no raw-file
  reread, no full-file bytes buffer, no disk-backed intermediate arrays,
  no second full dictionary, and no multiprocessing. Auxiliary patching
  buffers are bounded; Python integer byte counters support multi-GB files.
* On an unrecognized runtime layout, keep the completed standard raw pickle
  and automatically produce ZS with v3p1's standard second dump. This is
  explicitly reported. An I/O error aborts instead of being hidden.
* Keep the scalar operations used by v2p6 for score**2, mean**2, math.sqrt
  and Z-score normalization. Per-file float64 additions retain the original
  distance-sorted file order. No float32, approximate variance, FMA rewrite,
  or parallel reduction is used. rawCC/1024 is the source of the score.
* Stream input text, accumulate compact statistics, and directly build ONE
  full dictionary list. There is no array spool or full deepcopy.
  Standard pickle.dump's memo and the one full list do require memory
  proportional to total records. Unlike v3p0, memory is NOT O(particles).
* Compute top_N sums once and reuse them for all 61 histogram thresholds.
  Optional STAR/search output is still streamed; --max_cpu controls only
  optional search-file writing.
* Use a NEW <prefix>_pick_cache_v3p3.npz with runtime/input provenance.
  Earlier sidecars are never reused. Existing .pkl files without a matching
  v3p3 sidecar are regenerated, even without --regenerate_pickel. Threshold
  changes can reuse scores only while BOTH full pickle files still match.
* For an exact comparison, run both versions with --regenerate_pickel in
  the SAME Python/NumPy/SciPy environment, using the SAME input index/order,
  input files, best_string and diameter. Pickle bytes are runtime-dependent.
  --verify_against_prefix OLD_PREFIX compares both complete files using
  SHA-256 and fails if either differs. No reference pickle is executed.
* Preserve the legacy range(len(first_file_dictionary)) normalization and
  selection bound. Serials are zero-based physical STAR line numbers.
  Entries beyond that bound stay RAW in the Z-score pickle, as in v2p6.
  Inconsistent normalized serial coverage and negative variance remain
  errors; zero-variance normalization retains the original NaN behavior.
* --tmpdir is accepted for command-line compatibility but is no longer used
  for intermediate arrays. Both pickle files are staged before replacement.
  Partial new pickle data is not committed on an input, normalization or
  serialization error.
"""

